function ikon(nama, kelas = "") {
  const isi = IKON_PATH[nama];
  if (!isi) return "";
  return `<svg class="ikon ${kelas}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${isi}</svg>`;
}

/** Ganti semua <i data-ikon="..."> di halaman dengan SVG-nya. */
function pasangIkon(akar = document) {
  akar.querySelectorAll("i[data-ikon]").forEach((el) => {
    el.outerHTML = ikon(el.dataset.ikon, el.className);
  });
}
pasangIkon();
